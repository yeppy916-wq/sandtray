const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const html=fs.readFileSync(__dirname+'/../index.html','utf8');
const js=html.match(/<script id="game">([\s\S]*?)<\/script>/)[1];
new vm.Script(js);
const env={};vm.createContext(env);vm.runInContext(js,env);
const c=env.SandtrayCore,s=c.demoScene();
assert.equal(c.findPath(s).path,null,'closed gate blocks arrival');
s.objects[6*c.COLS+14].open=true;
assert.ok(c.findPath(s).path,'open gate provides route to bench');
s.objects[7*c.COLS+10].dir='v';
assert.equal(c.findPath(s).path,null,'bridge direction constrains walking');
console.log('Script syntax and gate / bridge navigation passed.');
const demo=c.storyDemoScene(),route=c.findPath(demo);
assert.ok(route.path.some(p=>p.x===demo.waypoints[0].x&&p.y===demo.waypoints[0].y),'visits waypoint');
const blank=c.emptyScene();assert.ok(c.validScene(blank));assert.ok(blank.terrain.every(t=>t===1));assert.equal(c.findPath(blank).reason,'markers');
const disconnected=c.storyDemoScene();disconnected.waypoints=[{x:2,y:2}];
for(const[x,y]of [[1,2],[3,2],[2,1],[2,3]])disconnected.objects[y*c.COLS+x]={type:'stone'};
assert.equal(c.findPath(disconnected).path,null,'unreachable waypoint blocks entire journey');assert.equal(c.findPath(disconnected).failedLeg,0);
const legacy=JSON.parse(JSON.stringify(c.storyDemoScene()));legacy.version=1;delete legacy.waypoints;delete legacy.materials;
const migrated=c.migrateScene(legacy);assert.ok(c.validScene(migrated));assert.equal(migrated.waypoints.length,1);assert.ok(c.findPath(migrated).path);
const oldClosed=JSON.parse(JSON.stringify(c.demoScene()));oldClosed.version=1;delete oldClosed.waypoints;delete oldClosed.materials;assert.ok(c.migrateScene(oldClosed));
console.log('Ocean defaults, ordered waypoint navigation, disconnected segments and legacy save migration passed.');
